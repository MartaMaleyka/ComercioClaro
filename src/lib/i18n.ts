const dictionaries: Record<Language, Partial<Record<MessageKey, string>>> = { es, zh, en };

export function translate(language: string, key: MessageKey, params?: Record<string, string | number>) {
  const dict = dictionaries[(language as Language) in dictionaries ? (language as Language) : "es"];
  let text = dict[key] ?? es[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) text = text.replaceAll(`{${k}}`, String(v));
  }
  return text;
}

